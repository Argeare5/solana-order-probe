"""Tables, figures and a Markdown summary from the metrics. Everything is written to one output directory
(report/generated by default) and is fully reproduced from data/ by `python -m order_analysis`."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from . import background, metrics, network
from .load import Dataset

# Reference palette (light surface): categorical slots 1-2, text tokens, recessive grid
SURFACE = "#fcfcfb"
TEXT = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"
FEE_COLOR = "#2a78d6"
ARRIVAL_COLOR = "#eb6834"
# Bursts whose prices are independent of the send order; the reverse variant opposes the two on purpose and is
# reported on its own
INDEPENDENT_VARIANTS = ("main", "conflict")
LADDER_VARIANTS = ("main", "reverse", "conflict")


def _style() -> None:
    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "axes.edgecolor": GRID, "axes.labelcolor": TEXT_SECONDARY, "axes.titlecolor": TEXT,
        "xtick.color": TEXT_SECONDARY, "ytick.color": TEXT_SECONDARY, "text.color": TEXT,
        "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.spines.top": False,
        "axes.spines.right": False, "font.size": 9, "axes.titlesize": 10, "legend.frameon": False,
    })


def build(data: Dataset, out: Path, seed: int, n_boot: int, n_perm: int, min_pairs: int, min_bursts: int = 5) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    (out / "figures").mkdir(exist_ok=True)
    rng = np.random.default_rng(seed)
    # Verdicts come from the direct path only; probes sent through an RPC node are compared on their own
    all_probes = data.probes
    probes = all_probes[all_probes["path"] == "quic"] if not all_probes.empty else all_probes
    summary: dict = {"runs": sorted(data.run_dirs), "seed": seed, "bootstrap": n_boot, "permutations": n_perm,
                     "min_pairs": min_pairs, "min_bursts": min_bursts}

    # The network around the measurements: read-only records, present even before any live run
    ingress = network.tpu_ingress(data.data_dir)
    ingress.to_csv(out / "tpu_ingress.csv", index=False)
    hand_over = network.hand_over(data.data_dir)
    hand_over.to_csv(out / "hand_over_by_client.csv", index=False)
    positions = network.slot_positions(data.data_dir)
    positions.to_csv(out / "slot_duration_by_position.csv", index=False)
    network_md = _network_markdown(ingress, hand_over, positions)

    if probes.empty:
        (out / "summary.md").write_text("# Results (generated)\n\nNo live mainnet runs in the data yet.\n\n" + network_md)
        summary["validators"] = []
        (out / "summary.json").write_text(json.dumps(summary, indent=2))
        return summary

    # Delivery: how many probes landed, in the window, and next to another probe of their burst
    landed_groups = metrics.landed_groups(probes)
    delivery = probes.groupby(["client", "identity"]).agg(
        sent=("signature", "size"),
        send_errors=("send_error", lambda s: s.notna().sum()),
        tpu_acked=("tpu_ack", lambda s: (s == "acked").sum()),
        landed=("landed_slot", lambda s: s.notna().sum()),
        in_window=("in_window", "sum"),
        landed_after_collection=("landed_late", "sum"),
        failed=("failed", "sum"),
    )
    delivery.insert(0, "bursts", probes.drop_duplicates(["run_id", "burst"]).groupby(["client", "identity"]).size())
    delivery["comparable"] = landed_groups.groupby(["client", "identity"]).size().reindex(delivery.index).fillna(0).astype(int)
    delivery.to_csv(out / "delivery.csv")

    pairs = metrics.pairs(probes)
    pairs.to_csv(out / "pairs.csv", index=False)
    taus = metrics.kendall(probes)
    taus.to_csv(out / "kendall_per_block.csv", index=False)

    def assess(subset: pd.DataFrame, pair_subset: pd.DataFrame) -> dict:
        ladder = subset[subset["variant"].isin(INDEPENDENT_VARIANTS)]
        null = subset[subset["variant"] == "null"]
        fee = metrics.share(ladder, "fee", rng, n_boot, n_perm)
        arrival_null = metrics.share(null, "arrival", rng, n_boot, n_perm)
        arrival_main = metrics.share(subset[subset["variant"] == "main"], "arrival", rng, n_boot, n_perm)
        payer_null = metrics.share(null, "payer", rng, n_boot, n_perm)
        reverse = subset[subset["variant"] == "reverse"]
        conflict = pair_subset[(pair_subset["variant"] == "conflict") & pair_subset["fee_agree"].notna()] if not pair_subset.empty else pair_subset
        row = {
            "verdict": metrics.verdict(fee, arrival_null, payer_null, min_pairs, min_bursts),
            **{f"fee_{k}": v for k, v in vars(fee).items()},
            **{f"arrival_null_{k}": v for k, v in vars(arrival_null).items()},
            **{f"arrival_main_{k}": v for k, v in vars(arrival_main).items()},
            **{f"payer_null_{k}": v for k, v in vars(payer_null).items()},
            "reverse_fee_share": metrics.share(reverse, "fee", rng, n_boot, 200).share,
            # The same fee share when the burst went out before the window (the leader holds it and schedules it
            # at once) and inside it (probes stream in while the leader builds)
            "fee_share_fired_before_window": metrics.share(ladder[ladder["fire_vs_observed_ms"] < 0], "fee", rng, 200, 1).share,
            "fee_share_fired_in_window": metrics.share(ladder[ladder["fire_vs_observed_ms"] >= 0], "fee", rng, 200, 1).share,
            "conflict_pairs_fee_share": float(conflict[conflict["conflict"]]["fee_agree"].mean()) if len(conflict) else np.nan,
            "nonconflict_pairs_fee_share": float(conflict[~conflict["conflict"]]["fee_agree"].mean()) if len(conflict) else np.nan,
            "tau_fee_median": float(taus.loc[taus.index.isin(subset_tau_index(taus, subset)), "tau_fee"].median()),
        }
        if not pair_subset.empty:
            row.update({f"logit_{k}": v for k, v in metrics.logistic(pair_subset[pair_subset["variant"].isin(INDEPENDENT_VARIANTS)], rng).items()})
        return row

    validators = []
    for (client, identity), subset in probes.groupby(["client", "identity"]):
        pair_subset = pairs[pairs["identity"] == identity] if not pairs.empty else pairs
        validators.append({"client": client, "identity": identity, **assess(subset, pair_subset)})
    validators_df = pd.DataFrame(validators)
    validators_df.to_csv(out / "validators.csv", index=False)

    rpc_rows = []
    for (client, identity), subset in all_probes[all_probes["path"] == "rpc"].groupby(["client", "identity"]):
        fee = metrics.share(subset[subset["variant"].isin(INDEPENDENT_VARIANTS)], "fee", rng, n_boot, n_perm)
        arrival = metrics.share(subset[subset["variant"] == "null"], "arrival", rng, n_boot, n_perm)
        rpc_rows.append({"client": client, "identity": identity, "sent": len(subset),
                         "landed": int(subset["landed_slot"].notna().sum()),
                         **{f"fee_{k}": v for k, v in vars(fee).items()},
                         **{f"arrival_null_{k}": v for k, v in vars(arrival).items()}})
    rpc_df = pd.DataFrame(rpc_rows)
    rpc_df.to_csv(out / "rpc_path.csv", index=False)

    clients = []
    for client, subset in probes.groupby("client"):
        pair_subset = pairs[pairs["client"] == client] if not pairs.empty else pairs
        clients.append({"client": client, "validators": subset["identity"].nunique(), **assess(subset, pair_subset)})
    clients_df = pd.DataFrame(clients)
    clients_df.to_csv(out / "clients.csv", index=False)

    # The shares under each firing condition: when the burst reached the leader (planned offset from the window's
    # start) and how far apart its probes were sent
    condition_rows = []
    for (client, offset, spacing), subset in probes.groupby(["client", "offset_ms", "spacing_ms"]):
        fee = metrics.share(subset[subset["variant"].isin(INDEPENDENT_VARIANTS)], "fee", rng, 200, 1)
        arrival = metrics.share(subset[subset["variant"] == "null"], "arrival", rng, 200, 1)
        condition_rows.append({"client": client, "offset_ms": offset, "spacing_ms": spacing,
                               "fee_share": fee.share, "fee_pairs": fee.pairs, "fee_bursts": fee.bursts,
                               "arrival_null_share": arrival.share, "arrival_null_pairs": arrival.pairs})
    conditions_df = pd.DataFrame(condition_rows)
    conditions_df.to_csv(out / "by_condition.csv", index=False)

    # Timing: when bursts went out relative to the window's first shred, by planned offset
    bursts = data.bursts
    timing = bursts.groupby("offset_ms")["fire_vs_observed_ms"].describe(percentiles=[0.1, 0.5, 0.9])
    timing["from_parallel_stream"] = bursts.groupby("offset_ms")["fire_timing_source"].apply(
        lambda s: int((s == "slot stream recorded alongside").sum()))
    timing.to_csv(out / "timing.csv")
    slot_in_window = probes.dropna(subset=["landed_slot"]).assign(
        slot_in_window=lambda d: d["landed_slot"].astype(int) - d["window_start"]
    )
    landing = slot_in_window.groupby(["offset_ms", "slot_in_window"]).size().unstack(fill_value=0)
    landing.to_csv(out / "landing_slot_in_window.csv")

    blocks = background.block_rows(data)
    blocks.to_csv(out / "background_blocks.csv", index=False)

    _style()
    _figure_shares(validators_df, out / "figures" / "shares_by_validator.png")
    _figure_positions(probes, out / "figures" / "position_vs_price.png", "fee")
    _figure_positions(probes, out / "figures" / "position_vs_send_order.png", "arrival")
    _figure_timing(bursts, out / "figures" / "fire_timing.png")

    summary.update({
        "validators": validators_df.replace({np.nan: None}).to_dict("records"),
        "clients": clients_df.replace({np.nan: None}).to_dict("records"),
        "probes_sent": int(len(probes)),
        "probes_landed": int(probes["landed_slot"].notna().sum()),
    })
    (out / "summary.json").write_text(json.dumps(summary, indent=2, default=float))
    rpc_md = ""
    if not rpc_df.empty:
        rpc_md = "\n".join(["## Through an RPC node (comparison path)", "",
                             "| Client | Validator | Sent | Landed | Higher price first | Sent earlier first (equal price) |",
                             "| --- | --- | --- | --- | --- | --- |"]
                            + [f"| {r['client']} | `{r['identity']}` | {r['sent']} | {r['landed']} | {_fmt_share(r, 'fee')} | "
                               f"{_fmt_share(r, 'arrival_null')} |" for _, r in rpc_df.iterrows()]) + "\n\n"
    sessions_df = _sessions(probes, blocks, data.runs, rng)
    sessions_df.to_csv(out / "by_session.csv", index=False)
    (out / "summary.md").write_text(_markdown(delivery, validators_df, clients_df, timing, blocks, summary) + "\n"
                                    + _conditions_markdown(conditions_df) + _sessions_markdown(sessions_df) + rpc_md
                                    + network_md)
    return summary


def subset_tau_index(taus: pd.DataFrame, subset: pd.DataFrame) -> pd.Index:
    keys = set(zip(subset["run_id"], subset["burst"]))
    return taus.index[[k in keys for k in zip(taus["run_id"], taus["burst"])]]


def _short(identity: str) -> str:
    return f"{identity[:4]}…{identity[-4:]}"


def _figure_shares(df: pd.DataFrame, path: Path) -> None:
    """Dot plot with 95% intervals: share of pairs ordered by price (ladder bursts) and by send time (null bursts)."""
    df = df.sort_values(["client", "identity"]).reset_index(drop=True)
    fig, ax = plt.subplots(figsize=(7.5, 0.42 * len(df) + 1.4))
    y = np.arange(len(df))
    for column, color, label, dy in (("fee", FEE_COLOR, "higher price first (price ladder bursts)", -0.12),
                                     ("arrival_null", ARRIVAL_COLOR, "sent earlier first (equal-price bursts)", 0.12)):
        share, low, high = (df[f"{column}_{k}"].to_numpy(dtype=float) for k in ("share", "low", "high"))
        ax.errorbar(share, y + dy, xerr=[share - low, high - share], fmt="o", color=color, ms=6, lw=1.5,
                    capsize=0, label=label, mec=SURFACE, mew=1)
    ax.axvline(0.5, color=TEXT_SECONDARY, lw=1, ls="--")
    ax.text(0.5, -0.9, "no rule", ha="center", va="bottom", color=TEXT_SECONDARY, fontsize=8)
    ax.set_yticks(y, [f"{c}  {_short(i)}" for c, i in zip(df["client"], df["identity"])])
    ax.set_xlim(0, 1.02)
    ax.set_ylim(len(df) - 0.5, -1)
    ax.set_xlabel("share of within-block probe pairs that follow the rule")
    ax.legend(loc="upper left", bbox_to_anchor=(0.0, -0.08 - 0.5 / max(len(df), 1)), ncol=1)
    ax.set_title("Which rule each leader follows inside its block", loc="left")
    fig.tight_layout()
    fig.savefig(path, dpi=160, bbox_inches="tight")
    plt.close(fig)


def _figure_positions(probes: pd.DataFrame, path: Path, rule: str) -> None:
    """Small multiples, one panel per validator: a probe's rank by the rule's label against its rank in the block,
    both within its block and scaled to 0-1. Points on the rising diagonal follow the rule."""
    groups = metrics.landed_groups(probes)
    groups = groups[groups["variant"].isin(INDEPENDENT_VARIANTS)] if rule == "fee" else groups[groups["variant"] == "null"]
    if groups.empty:
        return
    rows = []
    for _, g in groups.groupby(metrics.GROUP):
        n = len(g)
        label = metrics.LABELS[rule](g)
        rows.append(pd.DataFrame({
            "identity": g["identity"], "client": g["client"],
            "label_rank": (label.rank(method="average", ascending=False) - 1) / (n - 1),
            "position_rank": (g["block_index"].rank(method="average") - 1) / (n - 1),
        }))
    d = pd.concat(rows)
    panels = d.groupby(["client", "identity"])
    cols = min(4, len(panels))
    rows_n = int(np.ceil(len(panels) / cols))
    fig, axes = plt.subplots(rows_n, cols, figsize=(2.3 * cols, 2.3 * rows_n + 0.6), squeeze=False, sharex=True, sharey=True)
    jitter = np.random.default_rng(0)
    for ax, ((client, identity), g) in zip(axes.flat, panels):
        ax.plot([0, 1], [0, 1], color=GRID, lw=1.5, zorder=0)
        ax.scatter(g["label_rank"] + jitter.normal(0, 0.012, len(g)), g["position_rank"] + jitter.normal(0, 0.012, len(g)),
                   s=12, color=FEE_COLOR if rule == "fee" else ARRIVAL_COLOR, alpha=0.45, linewidths=0)
        ax.set_title(f"{client}\n{_short(identity)}", fontsize=8, loc="left")
        ax.set_xlim(-0.05, 1.05)
        ax.set_ylim(1.05, -0.05)
    for ax in list(axes.flat)[len(panels):]:
        ax.set_visible(False)
    what = "price rank (0 = highest)" if rule == "fee" else "send rank (0 = first sent)"
    fig.supxlabel(what, fontsize=9, color=TEXT_SECONDARY)
    fig.supylabel("place in block among the burst's probes (0 = first)", fontsize=9, color=TEXT_SECONDARY)
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def _figure_timing(bursts: pd.DataFrame, path: Path) -> None:
    """When bursts went out relative to the observed first shred of the window, by planned offset."""
    d = bursts.dropna(subset=["fire_vs_observed_ms"])
    if d.empty:
        return
    fig, ax = plt.subplots(figsize=(6.5, 2.8))
    bins = np.arange(np.floor(d["fire_vs_observed_ms"].min() / 25) * 25, d["fire_vs_observed_ms"].max() + 25, 25)
    for (offset, g), color in zip(d.groupby("offset_ms"), (FEE_COLOR, ARRIVAL_COLOR)):
        ax.hist(g["fire_vs_observed_ms"], bins=bins, histtype="step", lw=2, color=color, label=f"planned {offset:+.0f} ms")
        ax.axvline(offset, color=color, lw=1, ls=":")
    ax.axvline(0, color=TEXT_SECONDARY, lw=1)
    ax.set_xlabel("first probe sent − window's first shred at the RPC node (ms)")
    ax.set_ylabel("bursts")
    ax.legend(loc="upper left")
    ax.set_title("Fire timing against the observed window start", loc="left")
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def _fmt_share(row: pd.Series, prefix: str) -> str:
    if row.get(f"{prefix}_pairs", 0) == 0 or pd.isna(row.get(f"{prefix}_share")):
        return "–"
    return (f"{row[f'{prefix}_share']:.2f} [{row[f'{prefix}_low']:.2f}, {row[f'{prefix}_high']:.2f}], "
            f"p={row[f'{prefix}_p_value']:.3g}, {int(row[f'{prefix}_pairs'])} pairs / {int(row[f'{prefix}_bursts'])} bursts")


def _markdown(delivery: pd.DataFrame, validators: pd.DataFrame, clients: pd.DataFrame, timing: pd.DataFrame,
              blocks: pd.DataFrame, summary: dict) -> str:
    lines = ["# Results (generated)", "",
             f"Runs: {', '.join(summary['runs'])}. Probes sent {summary['probes_sent']}, landed {summary['probes_landed']}.",
             f"Intervals: 95% cluster bootstrap over bursts ({summary['bootstrap']} draws); p: permutation test of block "
             f"positions ({summary['permutations']} permutations), seed {summary['seed']}. A rule is claimed when p < 0.01 "
             f"and the interval excludes 0.5, from at least {summary['min_pairs']} pairs in {summary['min_bursts']} bursts.", "",
             "## Verdict per validator", "",
             "| Client | Validator | Verdict | Higher price first (main, conflict) | Sent earlier first (equal price) | Payer-index control | Higher price first (reverse) |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for _, r in validators.sort_values(["client", "identity"]).iterrows():
        reverse = "–" if pd.isna(r["reverse_fee_share"]) else f"{r['reverse_fee_share']:.2f}"
        lines.append(f"| {r['client']} | `{r['identity']}` | {r['verdict']} | {_fmt_share(r, 'fee')} | "
                     f"{_fmt_share(r, 'arrival_null')} | {_fmt_share(r, 'payer_null')} | {reverse} |")
    lines += ["", "## Per client (pooled)", "",
              "| Client | Validators | Verdict | Higher price first | Sent earlier first (equal price) | Fee share: fired before / in window |",
              "| --- | --- | --- | --- | --- | --- |"]
    for _, r in clients.iterrows():
        split = " / ".join("–" if pd.isna(r[k]) else f"{r[k]:.2f}" for k in ("fee_share_fired_before_window", "fee_share_fired_in_window"))
        lines.append(f"| {r['client']} | {r['validators']} | {r['verdict']} | {_fmt_share(r, 'fee')} | {_fmt_share(r, 'arrival_null')} | {split} |")
    lines += ["", "## Delivery", "", delivery.to_markdown(), "",
              "## Fire timing (first probe sent − window's first shred, ms)", "", timing.to_markdown(floatfmt=".0f"), ""]
    if not blocks.empty:
        bg = blocks.groupby(["client", "identity"])["tau_reward_per_cost"].describe(percentiles=[0.5])[["count", "50%"]]
        lines += ["## Whole blocks: Kendall τ of position against reward per cost unit", "", bg.to_markdown(floatfmt=".2f"), ""]
    lines += ["Figures: `figures/shares_by_validator.png`, `figures/position_vs_price.png`, "
              "`figures/position_vs_send_order.png`, `figures/fire_timing.png`.", ""]
    return "\n".join(lines)


def _network_markdown(ingress: pd.DataFrame, hand_over: pd.DataFrame, positions: pd.DataFrame) -> str:
    lines = []
    if not ingress.empty:
        latest = ingress[ingress["snapshot"] == ingress["snapshot"].max()].sort_values("stake_share", ascending=False)
        lines += [f"## Where leaders take transactions in (snapshot {latest['snapshot'].iloc[0]})", "",
                  "A TPU host shared by many nodes and different from their own address is the ingress of an external "
                  "sequencer or block builder: probes sent to such a leader reach that ingress first.", "",
                  "| Client | Staked nodes | Stake | TPU hosts | TPU on the node's own host | Most nodes behind one TPU host |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for _, r in latest.iterrows():
            lines.append(f"| {r['client']} | {r['staked_nodes']} | {r['stake_share']:.1%} | {r['tpu_hosts']} | "
                         f"{r['tpu_on_own_host']} | {r['most_nodes_per_tpu_host']} |")
        lines.append("")
    if not positions.empty:
        longest = positions.groupby("calibration")["n"].sum().idxmax()
        p = positions[positions["calibration"] == longest]
        lines += [f"## Slot duration by position in the leader window (calibration {longest})", "",
                  "| Position | Slots | Median ms | p10 | p90 |", "| --- | --- | --- | --- | --- |"]
        for _, r in p.iterrows():
            lines.append(f"| {r['position_in_window']} | {r['n']} | {r['median']:.0f} | {r['p10']:.0f} | {r['p90']:.0f} |")
        lines.append("")
    if not hand_over.empty:
        longest = hand_over.groupby("calibration")["windows"].sum().idxmax()
        h = hand_over[hand_over["calibration"] == longest].sort_values("windows", ascending=False)
        lines += [f"## Window start by client of the leader (calibration {longest}, {h['minutes'].iloc[0]:g} min)", "",
                  "From the RPC node's first-shred timestamps: hand-over = first shred of the leader's first slot minus "
                  "that of the slot before; window = first shred of its last slot minus its first; clock error = the "
                  "slot clock's prediction of the window start 100 ms ahead minus the observed start (negative = the "
                  "window started later than predicted). Median [p10, p90], ms.", "",
                  "| Client | Windows | Skipped | Hand-over in | Window | Clock error |", "| --- | --- | --- | --- | --- | --- |"]

        def cell(r: pd.Series, key: str) -> str:
            if pd.isna(r[f"{key}_median"]):
                return "–"
            return f"{r[f'{key}_median']:.0f} [{r[f'{key}_p10']:.0f}, {r[f'{key}_p90']:.0f}]"

        for _, r in h.iterrows():
            lines.append(f"| {r['client']} | {r['windows']} | {r['skipped_windows']} | {cell(r, 'hand_over_in')} | "
                         f"{cell(r, 'window')} | {cell(r, 'clock_error')} |")
        lines.append("")
    return "\n".join(lines)


def _conditions_markdown(df: pd.DataFrame) -> str:
    """Per client, the fee share (main and conflict bursts) under each firing condition, with its pair count."""
    if df.empty:
        return ""
    conditions = sorted({(o, sp) for o, sp in zip(df["offset_ms"], df["spacing_ms"])})
    head = " | ".join(f"{o:+.0f} ms, {sp} ms apart" for o, sp in conditions)
    lines = ["## Higher price first, by firing condition", "",
             "Planned fire moment against the window's start, and the gap between sends. Share of within-block pairs "
             "of the main and conflict bursts with the higher price first (pairs in brackets).", "",
             f"| Client | {head} |", "| --- |" + " --- |" * len(conditions)]
    for client, g in df.groupby("client"):
        cells = []
        for o, sp in conditions:
            r = g[(g["offset_ms"] == o) & (g["spacing_ms"] == sp)]
            if r.empty or not r["fee_pairs"].iloc[0]:
                cells.append("–")
            else:
                cells.append(f"{r['fee_share'].iloc[0]:.2f} ({int(r['fee_pairs'].iloc[0])})")
        lines.append(f"| {client} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n\n"


def _sessions(probes: pd.DataFrame, blocks: pd.DataFrame, runs: pd.DataFrame, rng: np.random.Generator) -> pd.DataFrame:
    """Per run (a session at one time of day) and client: the fee share in all main and conflict bursts and in the
    cleanest condition (whole burst at the leader before its window, sent at most 10 ms apart), and the load of the
    target leaders' blocks."""
    started = dict(zip(runs.get("run_id", []), runs.get("started_at", [])))
    rows = []
    for (run_id, client), g in probes.groupby(["run_id", "client"]):
        ladder = g[g["variant"].isin(INDEPENDENT_VARIANTS)]
        clean = ladder[(ladder["offset_ms"] < 0) & (ladder["spacing_ms"] <= 10)]
        b = blocks[(blocks["run_id"] == run_id) & (blocks["client"] == client)] if not blocks.empty else blocks
        fee, fee_clean = metrics.share(ladder, "fee", rng, 200, 1), metrics.share(clean, "fee", rng, 200, 1)
        rows.append({
            "run_id": run_id, "started_at": started.get(run_id), "client": client,
            "fee_share": fee.share, "fee_pairs": fee.pairs, "fee_share_clean": fee_clean.share, "fee_pairs_clean": fee_clean.pairs,
            "block_transactions_median": float(b["transactions"].median()) if len(b) else np.nan,
            "block_compute_units_median": float(b["compute_units"].median()) if len(b) else np.nan,
        })
    return pd.DataFrame(rows)


def _sessions_markdown(df: pd.DataFrame) -> str:
    if df.empty or df["run_id"].nunique() < 2:
        return ""
    lines = ["## By session", "",
             "Each run is a session at one time of day. Fee share: main and conflict bursts (all conditions / whole burst "
             "before the window, ≤ 10 ms apart); block load: median transactions and compute units of the target "
             "leaders' blocks that held probes.", "",
             "| Session | Client | Fee share | Fee share, clean | Transactions per block | Compute units per block |",
             "| --- | --- | --- | --- | --- | --- |"]
    for _, r in df.sort_values(["client", "run_id"]).iterrows():
        def f(v, digits=2):
            return "–" if pd.isna(v) else f"{v:.{digits}f}"
        lines.append(f"| {r['run_id']} | {r['client']} | {f(r['fee_share'])} ({int(r['fee_pairs'])}) | "
                     f"{f(r['fee_share_clean'])} ({int(r['fee_pairs_clean'])}) | {f(r['block_transactions_median'], 0)} | "
                     f"{f(r['block_compute_units_median'] / 1e6, 1)} M |")
    return "\n".join(lines) + "\n\n"
